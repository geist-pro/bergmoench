//! Write the (service, method) index table for Swift and Kotlin.
//! cargo run --release --example gen_index -- <anki_descriptors.bin> <out.swift> <out.kt>
use std::fmt::Write;

use anki_proto_gen::get_services;
use prost_reflect::DescriptorPool;

fn lower_camel(s: &str) -> String {
    let mut out = String::new();
    let mut up = false;
    for c in s.chars() {
        if c == '_' { up = true } else if up { out.extend(c.to_uppercase()); up = false } else { out.push(c) }
    }
    out
}

fn main() {
    let args: Vec<String> = std::env::args().collect();
    let pool = DescriptorPool::decode(std::fs::read(&args[1]).unwrap().as_slice()).unwrap();
    let (_, services) = get_services(&pool);
    let head = "Generated by core/ffi/examples/gen_index.rs from Anki's proto files. Do not edit.";
    let mut swift = format!("// {head}\n\nstruct BackendMethod {{ let service: UInt32; let method: UInt32 }}\n\n");
    let mut kt = format!("// {head}\npackage app.kartei.core\n\nclass BackendMethod(val service: Int, val method: Int)\n\n");
    for s in &services {
        let name = s.name.trim_start_matches("Backend").trim_end_matches("Service");
        writeln!(swift, "enum {name}Methods {{").unwrap();
        writeln!(kt, "object {name}Methods {{").unwrap();
        for m in s.all_methods() {
            let n = lower_camel(&m.name);
            writeln!(swift, "    static let {n} = BackendMethod(service: {}, method: {})", s.index, m.index).unwrap();
            writeln!(kt, "    val {n} = BackendMethod({}, {})", s.index, m.index).unwrap();
        }
        swift.push_str("}\n\n");
        kt.push_str("}\n\n");
    }
    std::fs::write(&args[2], swift).unwrap();
    std::fs::write(&args[3], kt).unwrap();
    println!("{} services", services.len());
}
